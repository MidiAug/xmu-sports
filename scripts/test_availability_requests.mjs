import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import ts from "typescript";
const availabilityJs=ts.transpileModule(readFileSync("src/lib/availability.ts","utf8"),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const availabilityUrl=`data:text/javascript;base64,${Buffer.from(availabilityJs).toString('base64')}`;
const persistenceJs=ts.transpileModule(readFileSync("src/lib/availability-persistence.ts","utf8"),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const persistenceUrl=`data:text/javascript;base64,${Buffer.from(persistenceJs).toString('base64')}`;
const source=readFileSync("src/lib/availability-store.ts","utf8").replace('"./availability"',JSON.stringify(availabilityUrl)).replace('"./availability-persistence"',JSON.stringify(persistenceUrl));
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {createAvailabilityStore,createAvailabilityCache}=await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
let clock=0, calls=0;
const today={sport:"运动",venue:"场馆",date:"2026-10-23"}, tomorrow={...today,date:"2026-10-24"};
const row=(t,extra={})=>({ok:true,state:"availability_ready",cached:false,fetched_at:"fixture",slots:[],...t,...extra});
const both=t=>({...row(t),snapshots:{[today.date]:row(today),[tomorrow.date]:row(tomorrow)}});
const store=createAvailabilityStore(async t=>{calls++;return both(t);},()=>clock);
await store.get(today);
for(let i=0;i<20;i++) {await store.get(tomorrow);await store.get(today);}
assert.equal(calls,1,"Date switches use both-day cache without IPC");
await store.get(today,true);await store.get(tomorrow,true);assert.equal(calls,2);
clock+=5001;await store.get(tomorrow,true);assert.equal(calls,3);
let finish, requests=0;
const slow=createAvailabilityStore(t=>{requests++;return new Promise(resolve=>finish=()=>resolve(both(t)));});
const one=slow.get(today),two=slow.get(tomorrow);finish();await Promise.all([one,two]);assert.equal(requests,1);
let failures=0, healthy=false;
const failing=createAvailabilityStore(async t=>{failures++;if(!healthy)throw Error("offline");return both(t);},()=>clock);
await assert.rejects(failing.get(today),/offline/);
await assert.rejects(failing.get(tomorrow),/offline/);assert.equal(failures,1);
await assert.rejects(failing.get({...today,venue:"另一场馆"}),/offline/);assert.equal(failures,1,"Offline backoff applies across venue switches");
healthy=true;await failing.get(today,true);assert.equal(failures,2,"Explicit refresh bypasses automatic backoff");
let negatives=0;
const unpublished=createAvailabilityStore(async t=>{negatives++;return row(t,{state:"date_not_published"});},()=>clock);
await unpublished.get(today);await unpublished.get(today);assert.equal(negatives,1);
clock+=30001;await unpublished.get(today);assert.equal(negatives,2);
let oldFinish, fresh=false;
const reset=createAvailabilityStore(t=>fresh ? Promise.resolve(row(t,{account_fingerprint:"new"})) : new Promise(resolve=>oldFinish=()=>resolve(row(t,{account_fingerprint:"old"}))));
const stale=reset.get(today);reset.reset();fresh=true;await reset.get(today);oldFinish();await stale;
assert.equal(reset.peek(today).account_fingerprint,"new");
let account="a";
const accounts=createAvailabilityStore(async t=>row(t,{account_fingerprint:account}),()=>clock);
await accounts.get(today);account="b";await accounts.get(tomorrow);
assert.equal(accounts.peek(today),undefined,"New account cannot reuse the previous account snapshot");
console.log("Availability request checks passed: dual-day cache, single-flight, refresh cooldown, failure backoff, short negative cache and account reset");

let pendingFinish, pendingCalls=0;
const disposed=createAvailabilityStore(t=>{pendingCalls++;return new Promise(resolve=>pendingFinish=()=>resolve(row(t)));});
const waiting=[disposed.get(today),disposed.get(tomorrow)];disposed.dispose();pendingFinish();
await Promise.allSettled(waiting);assert.equal(pendingCalls,1,"Leaving a page cannot dispatch a queued fallback query");
let releaseFirst, selected="first", serialCalls=[];
const serial=createAvailabilityStore(t=>{serialCalls.push(t.venue);return serialCalls.length===1 ? new Promise(resolve=>releaseFirst=()=>resolve(row(t))) : Promise.resolve(row(t));},()=>clock,t=>t.venue===selected);
const a=serial.get({...today,venue:"first"});selected="skipped";
const b=serial.get({...today,venue:"skipped"});selected="last";
const c=serial.get({...today,venue:"last"});releaseFirst();await Promise.allSettled([a,b,c]);
assert.deepEqual(serialCalls,["first","last"],"Only the latest selected venue may leave the queue");

const shared=createAvailabilityCache();let tabRequests=0;
const sharedFetch=async t=>{tabRequests++;return both(t);};
const mounted=createAvailabilityStore(sharedFetch,()=>clock,()=>true,shared);
await mounted.get(today);mounted.dispose();
for(let i=0;i<5;i++) {
  const remounted=createAvailabilityStore(sharedFetch,()=>clock,()=>true,shared);
  assert.ok(remounted.peek(tomorrow));await remounted.get(tomorrow);remounted.dispose();
}
assert.equal(tabRequests,1,"Remounting tabs reuses the same snapshots");
let lateResolve, lateCalls=0;
const retained=createAvailabilityCache();
const lateFetch=t=>{lateCalls++;return new Promise(resolve=>lateResolve=()=>resolve(both(t)));};
const oldView=createAvailabilityStore(lateFetch,()=>clock,()=>true,retained);
const oldQuery=oldView.get(today);oldView.dispose();
const newView=createAvailabilityStore(lateFetch,()=>clock,()=>true,retained);
const joined=newView.get(tomorrow);lateResolve();await Promise.all([oldQuery,joined]);
assert.equal(lateCalls,1,"An unfinished query survives navigation and is joined on return");
assert.ok(newView.peek(today));
const retainedFailure=createAvailabilityCache();let expiredCalls=0;
const expiredFetch=async t=>{expiredCalls++;return {...row(t),ok:false,code:"SESSION_EXPIRED"};};
const expiredView=createAvailabilityStore(expiredFetch,()=>clock,()=>true,retainedFailure);
await expiredView.get(today);expiredView.dispose();
const retryView=createAvailabilityStore(expiredFetch,()=>clock,()=>true,retainedFailure);
assert.equal(retryView.needsLogin(),true);await retryView.get(tomorrow);assert.equal(expiredCalls,1);
const refreshed=createAvailabilityCache();let refreshes=0;
const freshFetch=async t=>{refreshes++;return both(t);};
const refreshView=createAvailabilityStore(freshFetch,()=>clock,()=>true,refreshed);
await refreshView.get(today,true);refreshView.dispose();
const returnView=createAvailabilityStore(freshFetch,()=>clock,()=>true,refreshed);
await returnView.get(tomorrow,true);assert.equal(refreshes,1,"Navigation cannot bypass refresh cooldown");
console.log("Availability tab lifecycle checks passed: retained cache, pending query, expired login and cooldown");

let preLoginFinish;
const loginCache=createAvailabilityCache();
const beforeLogin=createAvailabilityStore(t=>new Promise(resolve=>preLoginFinish=()=>resolve(row(t,{account_fingerprint:"before"}))),()=>clock,()=>true,loginCache);
const preLoginQuery=beforeLogin.get(today);beforeLogin.dispose();
const afterLogin=createAvailabilityStore(async t=>row(t,{account_fingerprint:"after"}),()=>clock,()=>true,loginCache);
afterLogin.reset();await afterLogin.get(today);preLoginFinish();await preLoginQuery;
assert.equal(afterLogin.peek(today).account_fingerprint,"after","A former tab cannot overwrite login reset with an old response");

let disk=null, diskNow=Date.parse("2026-10-23T10:00:00+08:00"), diskCalls=0;
const storage={getItem:()=>disk,setItem:(_key,value)=>disk=value};
const persistedRow=t=>({...row(t),fetched_at:new Date(diskNow).toISOString(),account_fingerprint:"persist-a",cookie:"must-not-persist"});
const diskFetch=async t=>{diskCalls++;return {...persistedRow(t),snapshots:{[today.date]:persistedRow(today),[tomorrow.date]:persistedRow(tomorrow)}};};
const diskCache=createAvailabilityCache(storage,()=>diskNow);
const firstProcess=createAvailabilityStore(diskFetch,()=>diskNow,()=>true,diskCache);
await firstProcess.get(today);assert.ok(disk);assert.ok(!disk.includes("must-not-persist"));
const restarted=createAvailabilityStore(diskFetch,()=>diskNow,()=>true,createAvailabilityCache(storage,()=>diskNow));
assert.ok(restarted.peek(today));await restarted.get(today);await restarted.get(tomorrow);
assert.equal(diskCalls,1,"A fresh app cache restores both dates without RPC");
diskNow+=86400000;
const nextDay=createAvailabilityStore(diskFetch,()=>diskNow,()=>true,createAvailabilityCache(storage,()=>diskNow));
assert.equal(nextDay.peek(today),undefined);assert.ok(nextDay.peek(tomorrow));await nextDay.get(tomorrow);
assert.equal(diskCalls,1,"Tomorrow remains cached after becoming today");
nextDay.reset();assert.equal(JSON.parse(disk).snapshots.length,0,"Login reset also clears persisted snapshots");
for(const broken of ['{',JSON.stringify({version:99,snapshots:[]}),JSON.stringify({version:1,account:"b",snapshots:[persistedRow(tomorrow)]})]) {
  disk=broken;const corrupt=createAvailabilityCache(storage,()=>diskNow);
  assert.equal(corrupt.cache.size,0,"Malformed or mixed-account disk data is ignored");
}
const denied=createAvailabilityCache({getItem:()=>null,setItem:()=>{throw Error("quota");}},()=>diskNow);
const limited=createAvailabilityStore(async t=>persistedRow(t),()=>diskNow,()=>true,denied);
await limited.get(tomorrow);assert.ok(limited.peek(tomorrow));assert.equal(limited.persistenceFailed(),true);
console.log("Availability persistence checks passed: restart, date rollover, login reset, corrupt cache, sensitive-field stripping and storage failure");
