import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
const source = readFileSync(new URL("../src/lib/booking-progress.ts", import.meta.url), "utf8");
const js = ts.transpileModule(source, {compilerOptions: {module: ts.ModuleKind.ESNext}}).outputText;
const { currentRunEvents, elapsedLabel, progressMessage, progressStep } = await import(`data:text/javascript;base64,${Buffer.from(js).toString("base64")}`);
const base = { task_id: "test", run_id: "run-new", ts: "2026-10-13T18:55:35.831+08:00" };
const spawn = { ...base, action: "spawn" };
const submit = { ...base, action: "http_phase", result: "submitting", ts: "2026-10-13T18:55:42.497+08:00" };
const done = { ...base, action: "done", result: "http_verified", ts: "2026-10-13T18:55:43.075+08:00", http: {verified:true, court:"02", order_id:756717} };
assert.equal(currentRunEvents([{...spawn, run_id:"old"}, spawn, submit, done], done).length, 3);
assert.equal(elapsedLabel([spawn, submit, done], false), "7.2 秒");
assert.equal(progressStep(submit), "submit");
assert.equal(progressStep({...submit, result:"waiting_slot_retry"}), "query");
assert.match(progressMessage({...submit, result:"waiting_slot_retry"}), /参数错误.*2 秒.*重试一次/);
assert.match(progressMessage(done), /已查到匹配订单/);
assert.match(progressMessage({...done, result:"http_already_reserved"}), /未重复提交/);
assert.match(progressMessage({...submit, result:"slot_ready", http:{court:"02"}}), /02 号场地/);
assert.match(progressMessage({...submit, result:"selecting_candidate", http:{candidate_index:1, target:{time:"20:00", end:"21:00", court:"03"}}}), /第 2 个候选.*03 号场地/);
assert.match(progressMessage({...submit, result:"candidate_rejected", http:{message:"名额已满"}}), /名额已满/);
assert.match(progressMessage({...submit, action:"fail", http:{message:"登录失效"}}), /登录失效/);
assert.match(progressMessage({...submit, result:"captcha_recognized"}), /识别完成/);
assert.match(progressMessage({...submit, result:"order_accepted"}), /继续查单/);
assert.equal(progressMessage({...done, result:"http_prepared"}), "预约预检通过，未提交订单");
assert.match(progressMessage({...submit, result:"runtime_ready"}), /兼容性检查通过/);
assert.equal(progressStep({...submit, result:"h5_entry_reused"}), "auth");
assert.match(progressMessage({...submit, result:"h5_entry_reused"}), /已有场馆入口有效.*账号核验通过/);
assert.match(progressMessage({...submit, result:"normal_ui_refreshing"}), /重新识别.*等待/);
assert.match(progressMessage({...submit, result:"normal_ui_reenter"}), /重新打开厦大体育.*场馆预约/);
assert.equal(progressStep({...submit,result:"normal_ui_scrolling"}),"auth");
assert.match(progressMessage({...submit,result:"normal_ui_scrolling"}),/首页.*滚动.*场馆预约/);
assert.match(progressMessage({...submit, result:"scheduled_h5_ready"}), /提前就绪/);
assert.match(progressMessage({...submit, result:"scheduled_h5_rechecking"}), /重新验证/);
assert.match(progressMessage({...submit, result:"scheduled_h5_reused"}), /继续定时预约/);
assert.equal(progressStep({...submit,result:"pre_submit_auth_recovering"}),"auth");
assert.match(progressMessage({...submit,result:"pre_submit_auth_recovering"}),/尚未提交.*恢复原账号/);
assert.match(progressMessage({...submit,result:"pre_submit_auth_restored"}),/原任务继续一次.*去重/);
assert.match(progressMessage({...submit, result:"runtime_reconnecting"}), /重新连接/);
assert.match(progressMessage({...submit, result:"scheduled_waiting_fire"}), /等待设定时间/);
for (const phase of ["submission_uncertain", "waiting_order_sync", "rechecking_orders", "order_check_retry", "order_reconciled", "order_unconfirmed"]) {
  assert.equal(progressStep({...submit, result:phase}), "order");
}
assert.match(progressMessage({...submit, result:"submission_uncertain"}), /自动查单.*不重复提交/);
assert.match(progressMessage({action:"fail",result:"SUBMIT_UNKNOWN"}), /待确认/);
assert.match(progressMessage({...submit,result:"waiting_order_sync",http:{check_attempt:2,check_total:5,retry_after_seconds:2}}), /第 2\/5 轮.*2 秒后查询/);
console.log("Booking progress checks passed, including delayed order reconciliation and unconfirmed results");
