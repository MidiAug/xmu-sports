import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import ts from "typescript";
const source=readFileSync(new URL("../src/lib/booking-plans.ts",import.meta.url),"utf8");
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext}}).outputText;
const {nextPlanRound,hasPlanActivity,weekdaysLabel}=await import(`data:text/javascript;base64,${Buffer.from(js).toString("base64")}`);
const rule=(id)=>({id,sport:"gym",venue:"new-venue",start:"20:00",end:"21:00",enabled:true});
const view={plans:{rules:[rule("first"),rule("second")],paused:false,attempts:[]},next:[{id:"second",date:"2026-11-03",fire_at:"2026-11-02T07:00:00+08:00"},{id:"first",date:"2026-11-02",fire_at:"2026-11-01T07:00:00+08:00"}]};
const original=structuredClone(view.next);
assert.equal(nextPlanRound(view).date,"2026-11-02");
assert.deepEqual(nextPlanRound(view).items.map(i=>i.id),["first"]);
assert.deepEqual(view.next,original,"summary must not reorder host data");
const frozen=(id,status)=>({status,task:{plan_id:id,sport:"健身房",venue:"原场馆",target_date:"2026-11-01",fire_at:"2026-10-31T07:00:00+08:00",target_time_start:"16:30",target_time_end:"18:00"}});
view.plans.attempts=[frozen("first","running"),frozen("second","queued")];
view.plans.rules=[];
assert.equal(hasPlanActivity(view),true,"deleted rules do not erase a frozen round");
const round=nextPlanRound(view);
assert.equal(round.date,"2026-11-01");
assert.equal(round.fireAt,"2026-10-31T07:00:00+08:00");
assert.deepEqual(round.items.map(i=>[i.id,i.venue,i.start]),[["first","原场馆","16:30"],["second","原场馆","16:30"]]);
view.plans.attempts=[frozen("first","unconfirmed")];view.next=[];
assert.equal(hasPlanActivity(view),true);assert.equal(nextPlanRound(view),null);
view.plans.attempts=[];
assert.equal(hasPlanActivity(view),false);assert.equal(hasPlanActivity(undefined),false);
assert.equal(weekdaysLabel([1,2,3,4,5,6,7]),"每天");
assert.equal(weekdaysLabel([1,2,3,4,5]),"工作日");assert.equal(weekdaysLabel([6,7]),"周末");
assert.equal(weekdaysLabel([1,3,5]),"每周一、三、五");
console.log("Plan presentation passed: upcoming order, frozen snapshots, removed rules, pending results and weekdays");
