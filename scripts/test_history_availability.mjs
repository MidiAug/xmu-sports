import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
const read=path=>readFileSync(new URL(`../${path}`,import.meta.url),"utf8");
const compile=source=>`data:text/javascript;base64,${Buffer.from(ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText).toString("base64")}`;
const time=compile(read("src/lib/time.ts"));
const human=compile(read("src/lib/format-human.ts").replace('"./time"',JSON.stringify(time)));
const {formatMonthDayWeekday}=await import(human);
assert.equal(formatMonthDayWeekday("2026-10-26"),"10月26日(周一)");
assert.equal(formatMonthDayWeekday("2026-11-01"),"11月1日(周日)");
const progress=compile(read("src/lib/booking-progress.ts"));
const {historySteps,historyTarget,historyStages}=await import(compile(read("src/lib/history-steps.ts").replace('"./booking-progress"',JSON.stringify(progress)).replace('"./format-human"',JSON.stringify(human))));
const phases=["authenticating","checking_orders","checking_orders","captcha","querying_slots","submitting","verifying_order"];
const events=phases.map((phase,i)=>({ts:`2026-10-23T07:00:0${i}+08:00`,task_id:"test",action:"http_phase",result:phase,http:{phase,target:{sport:"健身房",venue:"翔安健身房",date:"2026-10-24",time:"16:30",end:"18:00"}}}));
const steps=historySteps(events);
assert.equal(steps.length,6);
assert.equal(steps[1].k,2);
assert.equal(steps[1].elapsedMs,2000);
for(const text of ["验证登录","已有预约","验证码","实时场次","发送预约","匹配订单"]) assert.ok(steps.some(step=>step.lines[0].line.includes(text)));
assert.equal(historySteps([...events,{...events[0],action:"http_exchange"}]).length,6);
assert.ok(historyTarget(events).includes("2026-10-24"));
const repeated=["authenticating","normal_ui_opening",...Array.from({length:4},()=>["semantic_login_control","native_login_opening","uia_window_message"]).flat(),"normal_ui_http_ready","closing_miniprogram","normal_ui_closed","checking_orders","querying_slots"];
const grouped=historyStages(repeated.map((phase,i)=>({...events[0],ts:new Date(Date.parse(events[0].ts)+i*1000).toISOString(),result:phase,http:{phase}})));
assert.equal(grouped.filter(stage=>stage.key==="auth").length,1);
assert.ok(grouped[0].steps.length>5);
assert.ok(grouped[0].steps.flatMap(step=>step.lines).some(line=>line.line.includes("未移动光标")));
assert.equal(grouped.at(-1).key,"query");
const timed=["authenticating","worker_model_warming","worker_warmed","authenticating","worker_warm_rechecked","scheduled_waiting_fire","authenticating","querying_slots"];
const timedStages=historyStages(timed.map((phase,i)=>({...events[0],result:phase,ts:new Date(Date.parse(events[0].ts)+i*1000).toISOString(),http:{phase}})));
assert.deepEqual(timedStages.map(stage=>stage.key),["prepare","waiting","auth","query"]);
assert.equal(timedStages[0].steps.length,5);assert.equal(timedStages[2].label,"执行前校验");
const failure=historySteps([{...events[0],action:"fail",result:"API_REJECTED",http:{phase:"querying_slots",message:"参数错误"}}])[0].lines[0].line;
assert.match(failure,/实时场次.*停止.*参数错误/);
const {adminLockLabel,quotaLabel,isAdminLocked,availabilityAuthNeeded,slotOption,courtOption}=await import(compile(read("src/lib/availability.ts")));
const cell={court:"01",admin_locked:false,status:"available",reason:"",remaining:1,capacity:1};
const slot=cells=>({start:"16:30",end:"18:00",cells});
assert.equal(isAdminLocked(slot([{...cell,admin_locked:true}])),true);
assert.equal(isAdminLocked(slot([])),false);
assert.equal(isAdminLocked(slot([cell]),"missing"),false);
assert.equal(isAdminLocked(slot([{...cell,remaining:0}])),false);
assert.match(adminLockLabel(slot([{...cell,admin_locked:true}])),/^全部场地管理员锁定$/);
const mixed=slot([{...cell,admin_locked:true,remaining:99},{...cell,court:"02",remaining:0},{...cell,court:"03"},{...cell,court:"07",admin_locked:true}]);
assert.equal(isAdminLocked(mixed),false);
assert.match(adminLockLabel(mixed),/2\/4.*01、07 号场地/);
assert.match(quotaLabel(mixed),/^剩余 1 名额.*已满：02 号场地/);
assert.match(quotaLabel(slot([{...cell,remaining:0}])),/^名额已满/);
assert.doesNotMatch(quotaLabel(slot([{...cell,remaining:0}])),/管理员/);
assert.match(quotaLabel(slot([{...cell,status:"unknown"}])),/状态未知/);
const closedFull={...cell,status:"unavailable",remaining:0};
const closedEmpty={...cell,status:"unavailable",remaining:1};
assert.equal(courtOption(closedFull).badge,"已满");
assert.equal(courtOption(closedEmpty).badge,undefined);
assert.equal(slotOption(slot([closedFull])).badge,"已满");
assert.equal(slotOption(slot([closedFull,closedEmpty])).badge,undefined);
assert.match(quotaLabel(slot([closedFull])),/^名额已满/);
assert.match(quotaLabel(slot([closedFull,{...closedEmpty,court:"07"}])),/剩余 1.*已满：01/);
assert.equal(courtOption({...closedFull,admin_locked:true,status:"locked"}).badge,"已锁");
assert.notEqual(courtOption({...closedFull,capacity:0}).badge,"已满");
assert.match(adminLockLabel(slot([cell]),"02"),/未提供/);
assert.match(quotaLabel(slot([{...cell,court:"2号场",remaining:0}])),/已满：2号场$/);
assert.match(adminLockLabel(slot([{...cell,court:"健身房",admin_locked:true}]),"健身房"),/^健身房管理员锁定$/);
assert.equal(slotOption(slot([{...cell,admin_locked:true}])).badge,"全部锁定");
assert.equal(slotOption(mixed).badge,"部分锁定");
assert.equal(slotOption(slot([{...cell,remaining:0}])).disabled,false);
assert.equal(courtOption({...cell,remaining:0}).disabled,false);
assert.equal(courtOption({...cell,admin_locked:true}).disabled,true);
assert.equal(courtOption({...cell,status:"unknown"}).badge,undefined);
assert.equal(courtOption(cell).badge,undefined);
assert.equal(courtOption({...cell,admin_locked:true}).badge,"已锁");
assert.equal(courtOption({...cell,remaining:0}).badge,"已满");
for(const code of ["NO_ENTRY","INVALID_ENTRY","SESSION_EXPIRED","SESSION_READ_FAILED","NO_SESSION_COOKIE","HTTP_AUTH_UNVERIFIED"]) assert.equal(availabilityAuthNeeded({code}),true);
assert.equal(availabilityAuthNeeded({code:"NETWORK_ERROR"}),false);
assert.equal(availabilityAuthNeeded({code:"API_REJECTED",phase:"authenticating"}),true);
assert.equal(availabilityAuthNeeded({code:"API_REJECTED",phase:"querying_slots"}),false);
const clock=await import(compile(read("src/lib/collapse-step-cycles.ts").replace('"./format-human"',JSON.stringify(human))));
assert.equal(clock.formatStepClock("2026-10-22T23:00:10Z"),"07:00:10");
console.log("History semantics and availability distinctions passed");
